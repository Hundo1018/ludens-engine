#!/usr/bin/env python3
"""Embed an action map asset in a Mojo constant (ludens-engine #117), so a wasm64 module needs no file.

    pixi run -e wasm gen-actions                  # writes game/demo_actions.mojo from game/data/demo.actions
    pixi run -e wasm gen-actions -- --check       # exit 1 when the file on disk differs (the lint runs it)

The map's grammar is parsed by game/action_map.mojo (tests/action_map.mojo parses this same file); this script only embeds
the text and checks that every `key:` source names a key the shell can send (shell/web/keys.ts)."""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def shell_key_names() -> set[str]:
    """The DOM code names shell/web/keys.ts turns into key codes: the table, and the Key[A-Z] / Digit[0-9] patterns."""
    ts = (ROOT / "shell/web/keys.ts").read_text()
    table = re.search(r"const KEYS: Record<string, number> = \{(.*?)\};", ts, re.S)
    if not table:
        sys.exit("gen_actions: shell/web/keys.ts has no KEYS table")
    names = set(re.findall(r"\b([A-Za-z0-9]+):\s*\d+", table.group(1)))
    names |= {f"Key{c}" for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"} | {f"Digit{d}" for d in "0123456789"}
    return names


def render(src: Path, text: str) -> str:
    if '"""' in text:
        sys.exit(f"{src}: a triple quote cannot be embedded")
    return (
        '"""The demo game\'s default action map as text, so a wasm64 module needs no file. Generated by scripts/gen_actions.py from\n'
        f"{src.relative_to(ROOT).as_posix()}; do not edit by hand (`pixi run -e wasm lint` fails when this file is not what the generator writes).\"\"\"\n\n"
        f'comptime DEMO_ACTIONS_TEXT = """{text}"""\n'
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("map", nargs="?", default="game/data/demo.actions")
    ap.add_argument("-o", "--out", default="game/demo_actions.mojo")
    ap.add_argument("--check", action="store_true", help="exit 1 if the output file is not what would be written")
    a = ap.parse_args()
    src = ROOT / a.map
    text = src.read_text()
    known = shell_key_names()
    for n, line in enumerate(text.split("\n"), 1):
        for m in re.finditer(r"\bkey:(\w+)", line.split("#")[0]):
            if m.group(1) not in known:
                sys.exit(f"{a.map}:{n}: key:{m.group(1)} is not a key shell/web/keys.ts sends")
    out = render(src, text)
    dst = ROOT / a.out
    if a.check:
        if not dst.exists() or dst.read_text() != out:
            sys.exit(f"{a.out} is stale: run `pixi run -e wasm gen-actions`")
        return 0
    dst.write_text(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
