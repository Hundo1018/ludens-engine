#!/usr/bin/env python3
"""Render every style pipeline (tests/style_gallery_native.mojo) and lay the frames out as PNGs.

    pixi run -e wasm style-gallery                 # build/gallery/<name>.png and build/gallery/sheet_<n>.png
    pixi run -e wasm style-gallery -- --only crt   # frames whose name contains "crt"
    pixi run -e wasm style-gallery -- --doc        # also rewrite docs/STYLE_PIPELINES.md from the run's output
    pixi run -e wasm style-gallery -- --doc --check   # fail if that file is not what the run gives (CI)

The Mojo program writes build/gallery/<name>.rgba (W x H RGBA8, the size it prints) and one "style <name> ..." line per
frame; this script converts them and draws contact sheets of 4 x 4 frames with the names under them."""
import argparse
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import build_core  # noqa: E402

OUT = ROOT / "build/gallery"
DOC = ROOT / "docs/STYLE_PIPELINES.md"
KEYS = [" | passes: ", " | aux: ", " | stages: ", " | after: "]


def parse_style(line: str) -> list[str] | None:
    """["name", passes, aux, stages, after] from a "style <name> | passes: ... | after: ..." line."""
    if not line.startswith("style "):
        return None
    rest, cells = line[6:], []
    for k in KEYS:
        if k not in rest:
            return None
        head, rest = rest.split(k, 1)
        cells.append(head)
    return [c.strip() for c in cells + [rest]]


def doc_text(rows: list[list[str]], summary: str) -> str:
    cell = lambda c: c.replace("|", "\\|")
    out = [
        "# Style pipelines",
        "",
        "Generated by `pixi run -e wasm style-gallery -- --doc` from the output of `tests/style_gallery_native.mojo`;",
        "do not edit. How the parts are written and combined: [PIPELINES.md](PIPELINES.md).",
        "",
        "Each row is one render pipeline, a type `SceneRendererOf[passes, stages, aux]`. `passes` is the list drawn into",
        "the scene target, `aux` a second list drawn into its own target, `stages` the graph of full-frame stages after",
        "them. The test fails a row whose three columns are those of the default renderer with one stage added.",
        "",
        f"{summary}",
        "",
        "| # | pipeline | after | passes | aux | stages |",
        "|---:|---|---|---|---|---|",
    ]
    for i, r in enumerate(rows):
        out.append(f"| {i + 1} | `{r[0]}` | {cell(r[4])} | {cell(r[1])} | {cell(r[2])} | {cell(r[3])} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--cols", type=int, default=4)
    ap.add_argument("--rows", type=int, default=4)
    ap.add_argument("--doc", action="store_true", help="write docs/STYLE_PIPELINES.md")
    ap.add_argument("--check", action="store_true", help="with --doc: compare instead of writing")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.rgba"):
        old.unlink()
    exe = build_core.build_native("tests/style_gallery_native.mojo", ROOT / "build/style_gallery_native", asserts=True)
    proc = subprocess.run([str(exe), "--dump", a.only], cwd=ROOT, capture_output=True, text=True)
    sys.stdout.write(proc.stdout)
    sys.stderr.write(proc.stderr[-4000:])
    size = None
    names = []
    for line in proc.stdout.splitlines():
        w = line.split()
        if w[:1] == ["size"]:
            size = (int(w[1]), int(w[2]))
        if w[:1] == ["style"]:
            names.append(w[1])
    if size is None:
        return proc.returncode or 1
    thumbs = []
    for n in names:
        raw = (OUT / f"{n}.rgba").read_bytes()
        im = Image.frombytes("RGBA", size, raw).convert("RGB")
        im.save(OUT / f"{n}.png")
        thumbs.append((n, im))
    per = a.cols * a.rows
    tw, th = size[0] // 2, size[1] // 2
    for s in range(0, len(thumbs), per):
        page = thumbs[s:s + per]
        sheet = Image.new("RGB", (a.cols * tw, a.rows * (th + 14)), (24, 24, 24))
        d = ImageDraw.Draw(sheet)
        for i, (n, im) in enumerate(page):
            x, y = (i % a.cols) * tw, (i // a.cols) * (th + 14)
            sheet.paste(im.resize((tw, th), Image.LANCZOS), (x, y))
            d.text((x + 3, y + th + 1), n, fill=(235, 235, 235))
        sheet.save(OUT / f"sheet_{s // per}.png")
    if a.doc and not a.only:
        rows = [r for r in map(parse_style, proc.stdout.splitlines()) if r and r[0] != "plain"]
        summary = next((l for l in proc.stdout.splitlines() if l.startswith("[PASS]") or l.startswith("[FAIL]")), "")
        text = doc_text(rows, f"{len(rows)} pipelines; last run: `{summary}`.")
        if a.check:
            if not DOC.exists() or DOC.read_text() != text:
                print(f"style_gallery: {DOC.relative_to(ROOT)} is out of date; run `pixi run -e wasm style-gallery -- --doc`")
                return 1
        else:
            DOC.write_text(text)
            print("wrote", DOC.relative_to(ROOT))
    print("wrote", len(thumbs), "frames and", (len(thumbs) + per - 1) // per, "sheets to", OUT)
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
