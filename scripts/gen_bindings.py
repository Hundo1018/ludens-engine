"""Generate language bindings from embed/ludens.h (ROADMAP 17.78).

The C header is the single source: every `#define LD_*` constant, typedef,
struct and function prototype in it is parsed and written out as a Rust
module (`bindings/rust/ludens_sys.rs`: consts, `#[repr(C)]` structs, opaque
handle types, `extern "C"` declarations) and a C# file
(`bindings/csharp/Ludens.cs`: consts, sequential-layout structs, opaque
handle structs used through pointers, callbacks as
`delegate* unmanaged[Cdecl]` function pointers, `DllImport` externs). A
hand-written binding drifts the moment a function is added; these are
regenerated and checked instead.

Usage:
    python3 scripts/gen_bindings.py            # write both bindings
    python3 scripts/gen_bindings.py --check    # fail if the file is stale
    python3 scripts/gen_bindings.py --selftest # parser checks on a planted header
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "embed", "ludens.h")
RUST_OUT = os.path.join(ROOT, "bindings", "rust", "ludens_sys.rs")
CS_OUT = os.path.join(ROOT, "bindings", "csharp", "Ludens.cs")

SCALARS = {
    "int32_t": "i32",
    "int64_t": "i64",
    "uint32_t": "u32",
    "uint64_t": "u64",
    "uint8_t": "u8",
    "double": "f64",
    "float": "f32",
    "char": "core::ffi::c_char",
    "void": "core::ffi::c_void",
}


def parse(text):
    """(defines, typedef aliases, opaque structs, structs, fn typedefs, functions)."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    defines = []
    for m in re.finditer(r"^#define\s+(LD_\w+)\s+\(?(-?\d+)\)?\s*$", text, re.M):
        defines.append((m.group(1), int(m.group(2))))
    aliases = re.findall(r"^typedef\s+(\w+)\s+(\w+);", text, re.M)
    opaque = re.findall(r"^typedef\s+struct\s+(\w+)\s+\1;", text, re.M)
    structs = []
    for m in re.finditer(r"typedef\s+struct\s+(\w+)\s*\{(.*?)\}\s*\1\s*;", text, re.S):
        fields = []
        for line in m.group(2).split(";"):
            line = line.strip()
            if line:
                ty, name = line.rsplit(None, 1)
                fields.append((name, ty))
        structs.append((m.group(1), fields))
    fntypes = []
    for m in re.finditer(r"^typedef\s+(\w+)\s*\(\*(\w+)\)\((.*?)\);", text, re.M):
        fntypes.append((m.group(2), m.group(1), _params(m.group(3))))
    funcs = []
    for m in re.finditer(r"^(\w+)\s+(ld_\w+)\((.*?)\);", text, re.M):
        funcs.append((m.group(2), m.group(1), _params(m.group(3))))
    return defines, aliases, opaque, structs, fntypes, funcs


def _params(s):
    s = s.strip()
    if s in ("", "void"):
        return []
    out = []
    for p in s.split(","):
        p = p.strip()
        const = p.startswith("const ")
        if const:
            p = p[len("const "):]
        stars = p.count("*")
        p = p.replace("*", " ")
        ty, name = p.split()
        out.append((name, ty, stars, const))
    return out


RUST_KEYWORDS = {"fn", "type", "ref", "mod", "move", "box", "use", "impl", "in", "loop", "match", "self", "where", "struct", "enum", "trait", "crate", "super", "dyn", "async", "await"}


def _rust_name(n):
    return "r#" + n if n in RUST_KEYWORDS else n


def _rust_type(ty, stars=0, const=False, opaque=(), fnptrs=()):
    if ty in fnptrs:
        base = ty
    elif ty in opaque:
        base = ty
    elif ty in SCALARS:
        base = SCALARS[ty]
    else:
        base = ty  # an alias or struct defined in the module
    for _ in range(stars):
        base = ("*const " if const else "*mut ") + base
    return base


def rust(header_text):
    defines, aliases, opaque, structs, fntypes, funcs = parse(header_text)
    fnnames = [f[0] for f in fntypes]
    out = [
        "// Generated by scripts/gen_bindings.py from embed/ludens.h -- do not edit.",
        "// Regenerate with `python3 scripts/gen_bindings.py`; `--check` fails when stale.",
        "#![allow(non_camel_case_types, dead_code)]",
        "",
    ]
    for name, value in defines:
        ty = "u32" if name.startswith("LD_ABI_") else "i32"
        out.append("pub const %s: %s = %d;" % (name, ty, value))
    out.append("")
    for src, name in aliases:
        if src != "struct":
            out.append("pub type %s = %s;" % (name, SCALARS.get(src, src)))
    for name in opaque:
        out.append("#[repr(C)]")
        out.append("pub struct %s {" % name)
        out.append("    _private: [u8; 0],")
        out.append("}")
    for name, fields in structs:
        out.append("#[repr(C)]")
        out.append("#[derive(Clone, Copy, Debug, Default, PartialEq)]")
        out.append("pub struct %s {" % name)
        for fname, fty in fields:
            out.append("    pub %s: %s," % (fname, SCALARS.get(fty, fty)))
        out.append("}")
    for name, ret, params in fntypes:
        args = ", ".join(_rust_type(t, s, c, opaque, fnnames) for _, t, s, c in params)
        out.append("pub type %s = Option<unsafe extern \"C\" fn(%s) -> %s>;" % (name, args, SCALARS.get(ret, ret)))
    out.append("")
    out.append("extern \"C\" {")
    for name, ret, params in funcs:
        args = ", ".join("%s: %s" % (_rust_name(pn), _rust_type(t, s, c, opaque, fnnames)) for pn, t, s, c in params)
        r = "" if ret == "void" else " -> " + SCALARS.get(ret, ret)
        out.append("    pub fn %s(%s)%s;" % (name, args, r))
    out.append("}")
    return "\n".join(out) + "\n", len(funcs)


CS_SCALARS = {
    "int32_t": "int",
    "int64_t": "long",
    "uint32_t": "uint",
    "uint64_t": "ulong",
    "uint8_t": "byte",
    "double": "double",
    "float": "float",
    "char": "byte",
    "void": "void",
}

CS_KEYWORDS = {"out", "in", "ref", "object", "string", "params", "base", "event", "fixed", "lock", "operator", "checked", "default", "delegate", "internal", "is", "as", "new", "this", "base", "static", "class", "struct", "namespace", "using", "var", "char", "int", "long", "float", "double", "byte", "bool", "decimal"}


def _cs_name(n):
    return "@" + n if n in CS_KEYWORDS else n


def csharp(header_text):
    """The C# binding: `Ludens.Native`, unsafe, P/Invoke on "ludens"."""
    defines, aliases, opaque, structs, fntypes, funcs = parse(header_text)
    alias = {name: CS_SCALARS.get(src, src) for src, name in aliases if src != "struct"}
    fnmap = {}

    def ty(t, stars=0):
        if t in fnmap:
            base = fnmap[t]
        else:
            base = alias.get(t, CS_SCALARS.get(t, t))
        return base + "*" * stars

    for name, ret, params in fntypes:
        args = [ty(t, st) for _, t, st, _ in params] + [CS_SCALARS.get(ret, ret)]
        fnmap[name] = "delegate* unmanaged[Cdecl]<%s>" % ", ".join(args)
    out = [
        "// Generated by scripts/gen_bindings.py from embed/ludens.h -- do not edit.",
        "// Regenerate with `python3 scripts/gen_bindings.py`; `--check` fails when stale.",
        "// Needs <AllowUnsafeBlocks>true</AllowUnsafeBlocks> (C# 9+ function pointers).",
        "using System.Runtime.InteropServices;",
        "",
        "namespace Ludens",
        "{",
    ]
    for name in opaque:
        out.append("    public struct %s { }" % name)
    for name, fields in structs:
        out.append("    [StructLayout(LayoutKind.Sequential)]")
        out.append("    public struct %s" % name)
        out.append("    {")
        for fname, fty in fields:
            out.append("        public %s %s;" % (ty(fty), _cs_name(fname)))
        out.append("    }")
    out.append("    public static unsafe class Native")
    out.append("    {")
    out.append("        public const string Lib = \"ludens\";")
    for name, value in defines:
        t = "uint" if name.startswith("LD_ABI_") else "int"
        out.append("        public const %s %s = %d;" % (t, name, value))
    for name, ret, params in funcs:
        args = ", ".join("%s %s" % (ty(t, st), _cs_name(pn)) for pn, t, st, c in params)
        out.append("        [DllImport(Lib, CallingConvention = CallingConvention.Cdecl)]")
        out.append("        public static extern %s %s(%s);" % (ty(ret), name, args))
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n", len(funcs)


def selftest():
    planted = """
#define LD_ABI_MAJOR 0
#define LD_ERR_X (-9) /* c */
typedef struct ld_w ld_w;
typedef int64_t ld_h;
typedef struct ev { int64_t a; float b; } ev;
typedef int32_t (*cb)(ld_w* w, const ev* e, void* u);
int32_t ld_f(ld_w* w, const float* p, int64_t n, cb fn, void* u);
uint32_t ld_v(void);
"""
    text, n = rust(planted)
    fails = 0
    for want in [
        "pub const LD_ABI_MAJOR: u32 = 0;",
        "pub const LD_ERR_X: i32 = -9;",
        "pub type ld_h = i64;",
        "pub struct ld_w {",
        "    pub b: f32,",
        "pub type cb = Option<unsafe extern \"C\" fn(*mut ld_w, *const ev, *mut core::ffi::c_void) -> i32>;",
        "    pub fn ld_f(w: *mut ld_w, p: *const f32, n: i64, r#fn: cb, u: *mut core::ffi::c_void) -> i32;",
        "    pub fn ld_v() -> u32;",
    ]:
        if want not in text:
            print("selftest: missing %r" % want)
            fails += 1
    if n != 2:
        print("selftest: %d functions, want 2" % n)
        fails += 1
    cs, _ = csharp(planted)
    for want in [
        "        public const uint LD_ABI_MAJOR = 0;",
        "        public const int LD_ERR_X = -9;",
        "    public struct ld_w { }",
        "        public float b;",
        "        public static extern int ld_f(ld_w* w, float* p, long n, delegate* unmanaged[Cdecl]<ld_w*, ev*, void*, int> fn, void* u);",
        "        public static extern uint ld_v();",
    ]:
        if want not in cs:
            print("selftest: C# missing %r" % want)
            fails += 1
    print("gen_bindings selftest:", "PASS" if fails == 0 else "FAIL")
    return 1 if fails else 0


def main(argv):
    if "--selftest" in argv:
        return selftest()
    with open(HEADER) as f:
        header = f.read()
    text, n = rust(header)
    cs, _ = csharp(header)
    outs = [(RUST_OUT, text), (CS_OUT, cs)]
    if "--check" in argv:
        for path, want in outs:
            cur = open(path).read() if os.path.exists(path) else ""
            if cur != want:
                print("gen_bindings: %s is stale; run python3 scripts/gen_bindings.py" % os.path.relpath(path, ROOT))
                return 1
        print("gen_bindings: up to date (%d functions)" % n)
        return 0
    for path, want in outs:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(want)
        print("gen_bindings: wrote %s (%d functions)" % (os.path.relpath(path, ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
