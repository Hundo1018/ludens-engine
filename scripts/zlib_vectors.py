#!/usr/bin/env python3
"""Generate tests/test_inflate.mojo from Python's zlib (ROADMAP 17.63).

Each vector is produced by zlib (1.3.2 in the pixi env), and every error case is
first checked to be rejected by zlib itself, so the Mojo expectations come from
an independent decoder rather than from geometry/inflate.mojo.

Run from the repository root:

    pixi run python3 scripts/zlib_vectors.py            # write tests/test_inflate.mojo
    pixi run python3 scripts/zlib_vectors.py --stdout   # print instead

Plaintexts are the generators `ramp(n)` and `fox(n)`, mirrored in the Mojo file.
"""

import argparse
import pathlib
import sys
import zlib

FOX = b"the quick brown fox "


def ramp(n):
    return bytes((i * 37) % 251 for i in range(n))


def fox(n):
    return (FOX * (n // len(FOX) + 1))[:n]


def btype(z):
    """BTYPE of the first DEFLATE block of a zlib stream (byte 2, bits 1-2)."""
    return (z[2] >> 1) & 3


def zlib_rejects(z):
    try:
        zlib.decompress(z)
    except zlib.error:
        return True
    return False


def raw_rejects(z):
    try:
        zlib.decompressobj(-15).decompress(z)
    except zlib.error:
        return True
    return False


class Bits:
    """LSB-first bit writer; Huffman codes go MSB-first through `code`."""

    def __init__(self):
        self.out = bytearray()
        self.acc = 0
        self.n = 0

    def bits(self, v, k):
        for i in range(k):
            self.acc |= ((v >> i) & 1) << self.n
            self.n += 1
            if self.n == 8:
                self.out.append(self.acc)
                self.acc = 0
                self.n = 0

    def code(self, c, k):
        for i in reversed(range(k)):
            self.bits((c >> i) & 1, 1)

    def finish(self):
        if self.n:
            self.out.append(self.acc)
        return bytes(self.out)


def find_dynamic():
    for n in range(200, 4000, 50):
        for data in (ramp(n), fox(n)):
            for level in (6, 9):
                z = zlib.compress(data, level)
                if btype(z) == 2:
                    return data, z
    raise SystemExit("no dynamic-Huffman vector found in the search range")


def hexs(b):
    return b.hex()


def build():
    cases = {}

    stored = zlib.compress(ramp(300), 0)
    assert btype(stored) == 0
    cases["stored"] = stored

    co = zlib.compressobj(6, zlib.DEFLATED, 15, 8, zlib.Z_FIXED)
    fixed = co.compress(fox(200)) + co.flush()
    assert btype(fixed) == 1
    cases["fixed"] = fixed

    dyn_data, dynamic = find_dynamic()
    cases["dynamic"] = dynamic
    dyn_kind = "fox" if dyn_data == fox(len(dyn_data)) else "ramp"
    dyn_n = len(dyn_data)

    # Raw DEFLATE: a fixed block whose first symbol is a match at distance 1
    # with nothing yet output. zlib must reject it too.
    w = Bits()
    w.bits(1, 1)  # BFINAL
    w.bits(1, 2)  # BTYPE = fixed
    w.code(0b0000001, 7)  # length symbol 257 (length 3)
    w.code(0, 5)  # distance symbol 0 (distance 1)
    before_start = w.finish()
    assert raw_rejects(before_start)

    bad_adler = dynamic[:-1] + bytes([dynamic[-1] ^ 1])
    bad_header = bytes([dynamic[0], dynamic[1] ^ 1]) + dynamic[2:]
    truncated = dynamic[:-3]
    for name, z in (("bad_adler", bad_adler), ("bad_header", bad_header), ("truncated", truncated)):
        assert zlib_rejects(z), name

    # zlib accepts these with the same output; the Mojo side checks its own.
    empty_stored_raw = bytes([0x01, 0x00, 0x00, 0xFF, 0xFF])
    assert zlib.decompressobj(-15).decompress(empty_stored_raw) == b""
    reserved = bytes([0x07])
    assert raw_rejects(reserved)
    bad_len = bytes([0x01, 0x05, 0x00, 0x00, 0x00])
    assert raw_rejects(bad_len)

    return {
        "stored": (cases["stored"], "ramp", 300),
        "fixed": (cases["fixed"], "fox", 200),
        "dynamic": (cases["dynamic"], dyn_kind, dyn_n),
        "bad_adler": (bad_adler, None, 0),
        "bad_header": (bad_header, None, 0),
        "truncated": (truncated, None, 0),
        "before_start": (before_start, None, 0),
        "reserved": (reserved, None, 0),
        "bad_len": (bad_len, None, 0),
        "empty_raw": (empty_stored_raw, "empty", 0),
    }


TEMPLATE = '''# tier: unit
"""DEFLATE and zlib decoding (ROADMAP 17.63, `geometry.inflate`).

GENERATED by scripts/zlib_vectors.py from Python's zlib 1.3.2. Do not edit by
hand; rerun the script. Every compressed input below was accepted by zlib with
the output this file expects, and every rejected input was rejected by zlib.

Vectors: a stored block (level 0), a fixed-Huffman block (Z_FIXED), a
dynamic-Huffman block (BTYPE 2 found by search), the raw DEFLATE form of the
dynamic vector, the max_out limit, and error cases: Adler-32 mismatch, bad
header check, truncated stream, a distance before the output start, a reserved
block type, a stored length mismatch.
"""

from harness.runner import Suite
from geometry.inflate import inflate, zlib_inflate


def unhex(h: String) -> List[UInt8]:
    var b = h.as_bytes()
    var out = List[UInt8]()
    var i = 0
    while i + 1 < len(b):
        out.append(UInt8(_nib(b[i]) * 16 + _nib(b[i + 1])))
        i += 2
    return out^


def _nib(c: UInt8) -> Int:
    if c >= 97:
        return Int(c) - 87
    return Int(c) - 48


def ramp(n: Int) -> List[UInt8]:
    var out = List[UInt8]()
    for i in range(n):
        out.append(UInt8((i * 37) % 251))
    return out^


def fox(n: Int) -> List[UInt8]:
    var pat = String("the quick brown fox ")
    var b = pat.as_bytes()
    var out = List[UInt8]()
    for i in range(n):
        out.append(b[i % len(b)])
    return out^


def same(a: List[UInt8], b: List[UInt8]) -> Bool:
    if len(a) != len(b):
        return False
    for i in range(len(a)):
        if a[i] != b[i]:
            return False
    return True


def zlib_fails(d: List[UInt8]) -> Bool:
    try:
        _ = zlib_inflate(d)
    except:
        return True
    return False


def raw_fails(d: List[UInt8]) -> Bool:
    try:
        _ = inflate(d)
    except:
        return True
    return False


def main() raises:
    var s = Suite("inflate")

    var stored = unhex("{stored}")
    s.check(same(zlib_inflate(stored), ramp({stored_n})), "zlib stored block (level 0) decodes to the input")

    var fixed = unhex("{fixed}")
    s.check(same(zlib_inflate(fixed), fox({fixed_n})), "zlib fixed-Huffman block (Z_FIXED) decodes to the input")

    var dynamic = unhex("{dynamic}")
    s.check(same(zlib_inflate(dynamic), {dynamic_gen}({dynamic_n})), "zlib dynamic-Huffman block decodes to the input")

    var raw = List[UInt8]()
    for i in range(2, len(dynamic) - 4):
        raw.append(dynamic[i])
    s.check(same(inflate(raw), {dynamic_gen}({dynamic_n})), "raw DEFLATE of the dynamic vector decodes to the same input")

    s.check(same(inflate(unhex("{empty_raw}")), List[UInt8]()), "raw empty stored final block decodes to nothing")

    var lim_ok = True
    try:
        _ = zlib_inflate(dynamic, {dynamic_n} - 1)
        lim_ok = False
    except:
        pass
    s.check(lim_ok, "max_out below the output size raises")
    s.check(same(zlib_inflate(dynamic, {dynamic_n}), {dynamic_gen}({dynamic_n})), "max_out equal to the output size passes")

    s.check(zlib_fails(unhex("{bad_adler}")), "a corrupted Adler-32 trailer raises")
    s.check(zlib_fails(unhex("{bad_header}")), "a bad zlib header check raises")
    s.check(zlib_fails(unhex("{truncated}")), "a truncated zlib stream raises")
    s.check(raw_fails(unhex("{before_start}")), "a distance before the output start raises")
    s.check(raw_fails(unhex("{reserved}")), "a reserved block type (3) raises")
    s.check(raw_fails(unhex("{bad_len}")), "a stored length that fails its one's complement check raises")
    s.check(zlib_fails(List[UInt8]()), "an empty zlib stream raises")
    s.finish()
'''


def emit(vec):
    ex = {k: v[0].hex() for k, v in vec.items()}
    dyn_gen = "fox" if vec["dynamic"][1] == "fox" else "ramp"
    stored_n = vec["stored"][2]
    fixed_n = vec["fixed"][2]
    dynamic_n = vec["dynamic"][2]
    return TEMPLATE.format(
        stored=ex["stored"],
        fixed=ex["fixed"],
        dynamic=ex["dynamic"],
        empty_raw=ex["empty_raw"],
        bad_adler=ex["bad_adler"],
        bad_header=ex["bad_header"],
        truncated=ex["truncated"],
        before_start=ex["before_start"],
        reserved=ex["reserved"],
        bad_len=ex["bad_len"],
        stored_n=stored_n,
        fixed_n=fixed_n,
        dynamic_n=dynamic_n,
        dynamic_gen=dyn_gen,
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default="tests/test_inflate.mojo")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args()
    text = emit(build())
    if args.stdout:
        sys.stdout.write(text)
        return
    path = pathlib.Path(args.out)
    path.write_text(text)
    print(f"wrote {path} (zlib {zlib.ZLIB_RUNTIME_VERSION})")


if __name__ == "__main__":
    main()
