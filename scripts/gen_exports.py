#!/usr/bin/env python3
"""Generate shell/web/exports.d.ts from the @export defs in app/main.mojo.  --check fails if it is stale."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TS = {"UInt64": "bigint", "Int64": "bigint", "UInt32": "number", "Int32": "number",
      "Float64": "number", "Float32": "number"}


def render() -> str:
    src = (ROOT / "app/main.mojo").read_text()
    out = ["// Generated by scripts/gen_exports.py from the @export defs in app/main.mojo. Do not edit.",
           "// Pointers and u64 handles are bigint (wasm64); everything else is number.",
           "export interface AppExports {"]
    for name, args, ret in re.findall(r'@export\ndef (\w+)\((.*?)\) abi\("C"\)(?: -> (\w+))?:', src, re.S):
        params = []
        for part in re.split(r",\s*", " ".join(args.split())):
            if part:
                n, t = (x.strip() for x in part.split(":"))
                params.append(f"{n}: {TS[t]}")
        out.append(f"  {name}({', '.join(params)}): {TS[ret] if ret else 'void'};")
    return "\n".join(out + ["}", ""])


if __name__ == "__main__":
    path = ROOT / "shell/web/exports.d.ts"
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if path.exists() and path.read_text() == text else "exports.d.ts is stale: run scripts/gen_exports.py")
    path.write_text(text)
